def P(text="", style=None, align=None, indent=True, bold=False, size=None):
    p = doc.add_paragraph(style=style)
    if text:
        r = p.add_run(text)
        r.bold = bold
        if size:
            r.font.size = Pt(size)
    if align is not None:
        p.alignment = align
    if not indent:
        p.paragraph_format.first_line_indent = Cm(0)
    return p

def H(text, level=1):
    return doc.add_heading(text, level=level)

def caption(text):
    return P(text, align=WD_ALIGN_PARAGRAPH.CENTER, indent=False)

def pagebreak():
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

def add_figure(png, num, title, max_h_cm=22.5, max_w_cm=15.5):
    im = Image.open(png)
    w_px, h_px = im.size
    w_cm = min(max_w_cm, max_h_cm * w_px / h_px)
    P()
    pic_p = doc.add_paragraph()
    pic_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pic_p.paragraph_format.first_line_indent = Cm(0)
    pic_p.add_run().add_picture(png, width=Cm(w_cm))
    cap = caption(f"Рисунок {num} — {title}")
    # подпись рисунка размещается под рисунком по центру
    return cap

def clone_table(src_tbl, font_size=10):
    """Копирует таблицу лабораторной в курсовую с сохранением содержимого.

    Вставка выполняется в конец текущего тела документа (после последнего
    параграфа), что корректно работает при чередовании портретных и
    альбомных секций.
    """
    new = copy.deepcopy(src_tbl._tbl)
    body = doc.element.body
    sectPr = body.find(qn("w:sectPr"))
    if sectPr is not None:
        sectPr.addprevious(new)
    else:
        body.append(new)
    # уменьшим шрифт в больших таблицах
    from docx.table import Table
    tbl = Table(new, doc)
    for row in tbl.rows:
        for cell in row.cells:
            for p in cell.paragraphs:
                p.paragraph_format.first_line_indent = Cm(0)
                p.paragraph_format.line_spacing = 1.0
                for r in p.runs:
                    r.font.size = Pt(font_size)
    return tbl

